// Turns eval/results/raw.jsonl into eval/RESULTS.md.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { RESULTS_FILE, loadCases, type ResultLine } from "./run";

const results = readFileSync(RESULTS_FILE, "utf8").trim().split("\n").filter(Boolean).map((l) => JSON.parse(l) as ResultLine);
const cases = await loadCases();
const bugCases = cases.filter((c) => c.meta.bug);
const cleanCases = cases.filter((c) => !c.meta.bug);
const models = [...new Set(results.map((r) => r.model))];
const runs = [...new Set(results.map((r) => r.run))].sort();
const short = (m: string) => m.replace(/^openrouter:/, "");
const pct = (x: number) => `${Math.round(x * 100)}%`;
const usd = (x: number) => (x < 0.01 ? `$${x.toFixed(4)}` : `$${x.toFixed(3)}`);
const median = (xs: number[]) => {
  const s = [...xs].sort((a, b) => a - b);
  return s.length ? s[Math.floor(s.length / 2)]! : 0;
};

type Row = { model: string; recall: number; recallMin: number; recallMax: number; noiseClean: number; extraPerBugPr: number; cost: number; perReview: number; perCatch: number; p50: number; errors: number; reviews: number };
const rows: Row[] = models.map((model) => {
  const mine = results.filter((r) => r.model === model);
  const ok = mine.filter((r) => r.ok);
  const perRun = runs.map((run) => {
    const rr = ok.filter((r) => r.run === run && r.caught !== null);
    return rr.filter((r) => r.caught).length / bugCases.length;
  });
  const caught = ok.filter((r) => r.caught).length;
  const cost = mine.reduce((s, r) => s + r.costUsd, 0);
  const clean = ok.filter((r) => r.caught === null);
  const bug = ok.filter((r) => r.caught !== null);
  return {
    model,
    recall: perRun.reduce((a, b) => a + b, 0) / perRun.length,
    recallMin: Math.min(...perRun),
    recallMax: Math.max(...perRun),
    noiseClean: clean.length ? clean.reduce((s, r) => s + r.posted.length, 0) / clean.length : 0,
    extraPerBugPr: bug.length ? bug.reduce((s, r) => s + r.posted.length - (r.caught ? 1 : 0), 0) / bug.length : 0,
    cost,
    perReview: cost / Math.max(mine.length, 1),
    perCatch: caught ? cost / caught : Infinity,
    p50: median(ok.map((r) => r.ms)) / 1000,
    errors: mine.length - ok.length,
    reviews: mine.length,
  };
});
rows.sort((a, b) => b.recall - a.recall || a.perReview - b.perReview);

const out: string[] = [];
out.push("# Benchmark results", "");
out.push(`${bugCases.length} PRs with one planted bug each + ${cleanCases.length} clean PRs · ${runs.length} runs per model · same prompt and validation as production (\`min_severity: medium\`).`);
out.push(`A bug counts as caught when a posted comment lands within ±3 lines of it. Generated by \`bun eval/report.ts\` from \`eval/results/raw.jsonl\`.`, "");
out.push("| Model | Bugs caught (avg, range over runs) | Comments on clean PRs | Other comments per bug PR | Cost per review | Cost per bug caught | Median time | Errors |");
out.push("|---|---|---|---|---|---|---|---|");
for (const r of rows) {
  out.push(
    `| \`${short(r.model)}\` | **${pct(r.recall)}** (${pct(r.recallMin)}–${pct(r.recallMax)}) | ${r.noiseClean.toFixed(1)} | ${r.extraPerBugPr.toFixed(1)} | ${usd(r.perReview)} | ${Number.isFinite(r.perCatch) ? usd(r.perCatch) : "—"} | ${r.p50.toFixed(0)} s | ${r.errors}/${r.reviews} |`,
  );
}
out.push("", `Total spent on this benchmark: **${usd(results.reduce((s, r) => s + r.costUsd, 0))}** for ${results.length} reviews.`, "");

out.push("## By category (bugs caught, averaged over runs)", "");
const categories = [...new Set(bugCases.map((c) => c.meta.category))];
out.push(`| Model | ${categories.join(" | ")} |`, `|---|${categories.map(() => "---").join("|")}|`);
for (const r of rows) {
  const cells = categories.map((cat) => {
    const ids = new Set(bugCases.filter((c) => c.meta.category === cat).map((c) => c.meta.id));
    const rr = results.filter((x) => x.model === r.model && ids.has(x.case) && x.ok);
    return rr.length ? pct(rr.filter((x) => x.caught).length / rr.length) : "—";
  });
  out.push(`| \`${short(r.model)}\` | ${cells.join(" | ")} |`);
}

out.push("", "## Per case (runs that caught the bug)", "");
out.push(`| Case | Planted bug | ${rows.map((r) => `\`${short(r.model)}\``).join(" | ")} |`, `|---|---|${rows.map(() => "---").join("|")}|`);
for (const c of bugCases) {
  const cells = rows.map((r) => {
    const rr = results.filter((x) => x.model === r.model && x.case === c.meta.id && x.ok);
    return `${rr.filter((x) => x.caught).length}/${rr.length}`;
  });
  out.push(`| ${c.meta.id} | ${c.meta.bug!.summary} | ${cells.join(" | ")} |`);
}
out.push("", "Clean PRs (no planted bug): average comments posted", "");
out.push(`| Case | ${rows.map((r) => `\`${short(r.model)}\``).join(" | ")} |`, `|---|${rows.map(() => "---").join("|")}|`);
for (const c of cleanCases) {
  const cells = rows.map((r) => {
    const rr = results.filter((x) => x.model === r.model && x.case === c.meta.id && x.ok);
    return rr.length ? (rr.reduce((s, x) => s + x.posted.length, 0) / rr.length).toFixed(1) : "—";
  });
  out.push(`| ${c.meta.id} | ${cells.join(" | ")} |`);
}

writeFileSync(path.join(import.meta.dir, "RESULTS.md"), `${out.join("\n")}\n`);
console.log(out.slice(0, 6 + rows.length + 3).join("\n"));
